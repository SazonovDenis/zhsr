function buildFaults() {
  const groups: DictRec[] = [{ id: 'FAV', text: { ru: 'Частые неисправности' }, sort: 0 }]
  const types: DictRec[] = FAKE_FREQUENT.map(([name, severity], i) => ({
    id: `FAV-${i + 1}`,
    text: { ru: name },
    group: 'FAV',
    category: 'TECHNICAL',
    severity,
    service: null,
  }))
  FAKE_FAULT_GROUPS.forEach(([code, category, severity, name, items], g) => {
    groups.push({ id: code, text: { ru: name }, sort: g + 1 })
    items.split(';').forEach((item, i) => {
      types.push({ id: `${code}-${i + 1}`, text: { ru: item }, group: code, category, severity, service: null })
    })
  })
  FAKE_DICTS.FaultGroup = groups
  FAKE_DICTS.FaultType = types
}

buildFaults()
