import mitt from 'mitt'

/**
 * Общая шина событий приложения.
 *
 * Шина связывает части, которые не знают друг о друге: пункт меню сообщает, что его выбрали, а переход по маршруту
 * выполняет тот, кто умеет (layout). Данные между родителем и потомком шиной не передаются — для этого есть props
 * и emit компонента.
 *
 * Каждое событие описано в BusEvents: имя и тип данных проверяются при компиляции.
 */
export type BusEvents = {
  /** свернуть левое меню */
  'menu-collapse': void
  /** развернуть левое меню */
  'menu-expand': void
  /** выбран пункт меню; имя события задаётся в menu.json */
  [menuItem: `menu-${string}`]: void

  /** данные, влияющие на текущее состояние (счётчики меню), изменились — состояние нужно загрузить заново */
  'state-refresh': void

  /** связь с сервером восстановилась, и за время разрыва могли пропасть команды сервера */
  'connection-restored': void

  /** заявки на ремонт изменились (подана, отправлена из очереди, сменился статус) — списки загружаются заново */
  'requests-refresh': void

  /** справочник обновился целиком (id не задан) или обновилась одна его запись */
  'dict-refresh': { dictName: string; id?: string | number }
}

export const bus = mitt<BusEvents>()
