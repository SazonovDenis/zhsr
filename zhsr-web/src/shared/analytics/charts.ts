/** Диаграммы, которые видит текущий пользователь. Реактивно: зависит от currentUser. */
export function visibleCharts(): ChartDef[] {
  return isCrewOnly() ? CHARTS.filter((c) => c.crew) : CHARTS
}

/** Диаграмма по id; нет такой или пользователю она не видна — undefined. */
export function chartById(id: string): ChartDef | undefined {
  return visibleCharts().find((c) => c.id === id)
}
