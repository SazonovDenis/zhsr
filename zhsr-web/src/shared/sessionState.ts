/**
 * Состояние интерфейса, которое живёт в памяти приложения и относится к вошедшему пользователю: раскрытая группа
 * меню, отбор и прокрутка списков, загруженные варианты выбора. При выходе и при потере входа (forgetUser) всё это
 * сбрасывается к начальному: следующий вошедший начинает с чистого листа.
 *
 *   onSessionReset(() => { menuState.openGroup = null })
 *
 * Модуль со своим состоянием регистрирует сброс при загрузке; не загружен — сбрасывать в нём нечего.
 */
const resets: (() => void)[] = []

/** Зарегистрировать сброс состояния модуля. */
export function onSessionReset(reset: () => void): void {
  resets.push(reset)
}

/** Сбросить всё зарегистрированное состояние. */
export function resetSessionState(): void {
  resets.forEach((reset) => reset())
}
